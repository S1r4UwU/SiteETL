export const spectaclesParAnnee = () => {
  const groupes = new Map<number, Spectacle[]>();
  for (const s of spectacles) {
    const liste = groupes.get(s.annee) ?? [];
    liste.push(s);
    groupes.set(s.annee, liste);
  }
  return [...groupes.entries()].sort((a, b) => b[0] - a[0]);
};

export const spectacleParSlug = (slug: string) =>
  spectacles.find((s) => s.slug === slug);
